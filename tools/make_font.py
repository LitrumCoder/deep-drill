# shared shapes
for cyr, lat in {'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X'}.items():
    G[cyr] = G[lat]
G['Й'] = G['И']
G['Ё'] = G['Е']
ACCENT = {'Й': [' ### '], 'Ё': [' # # ']}

TABULAR = set('0123456789')


def glyph_name(ch):
    return 'space' if ch == ' ' else 'uni%04X' % ord(ch)


def build():
    chars = sorted(G.keys())
    order = ['.notdef', 'space'] + [glyph_name(c) for c in chars]
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder(order)
    cmap = {32: 'space', 0xA0: 'space'}
    for c in chars:
        cmap[ord(c)] = glyph_name(c)
        low = c.lower()
        if low != c and ord(low) not in cmap:
            cmap[ord(low)] = glyph_name(c)
    fb.setupCharacterMap(cmap)

    glyphs, metrics = {}, {}
    empty = TTGlyphPen(None).glyph()
    glyphs['.notdef'] = empty; metrics['.notdef'] = (5 * PX, 0)
    glyphs['space'] = empty; metrics['space'] = (4 * PX, 0)
    for c in chars:
        rows = G[c]
        width = max(len(r) for r in rows)
        rows = [r.ljust(width) for r in rows]
        cols = [i for i in range(width) if any(r[i] == '#' for r in rows)]
        lo, hi = (0, width - 1) if c in TABULAR or not cols else (min(cols), max(cols))
        pen = TTGlyphPen(None)
        allrows = [(y, r) for y, r in enumerate(rows)]
        for k, r in enumerate(ACCENT.get(c, [])):
            allrows.append((-1 - k, r.ljust(width)))
        for y, r in allrows:
            x = lo
            while x <= hi:
                if r[x] != '#':
                    x += 1
                    continue
                x0 = x
                while x <= hi and r[x] == '#':
                    x += 1
                # pixel row y (0 = cap top) -> font units, baseline at row 7
                top = (7 - y) * PX
                bot = top - PX
                l, rr = (x0 - lo) * PX, (x - lo) * PX
                pen.moveTo((l, bot)); pen.lineTo((l, top)); pen.lineTo((rr, top)); pen.lineTo((rr, bot)); pen.closePath()
        glyphs[glyph_name(c)] = pen.glyph()
        metrics[glyph_name(c)] = ((hi - lo + 2) * PX, 0)

    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=1000, descent=-250)
    fb.setupNameTable({'familyName': 'DrillPixel', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=1000, sTypoDescender=-250, sTypoLineGap=0, usWinAscent=1000, usWinDescent=250, sxHeight=875, sCapHeight=875)
    fb.setupPost()
    fb.save(str(ROOT / 'promo' / 'drillpixel.ttf'))
    fb.font.flavor = 'woff'
    fb.font.save(str(OUT / 'drillpixel.woff'))
    print('glyphs', len(chars), '->', OUT)


build()
